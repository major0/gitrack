package web

import (
	"bytes"
	"fmt"
	"html/template"
	"path"
	"strings"
	"time"

	"github.com/alecthomas/chroma/v2"
	"github.com/alecthomas/chroma/v2/formatters/html"
	"github.com/alecthomas/chroma/v2/lexers"
	"github.com/alecthomas/chroma/v2/styles"
)

const (
	// defaultHighlightStyle is used when no style is configured or the
	// configured name is unknown.
	defaultHighlightStyle = "github"
	// maxHighlightBytes is the largest file that is highlighted. Lexers are
	// regular-expression machines, so cost grows with input; past this a file is
	// shown as plain text (ADR-0043).
	maxHighlightBytes = 128 << 10
	// maxHighlightTotal is how many bytes of source one generation will
	// highlight in all. Highlighting costs roughly a second per 300 KB, so this
	// caps the extra time near two minutes however large the repository is. It is
	// a byte count, not a clock, so the same repository always highlights the same
	// files (files are visited in git's fixed path order).
	maxHighlightTotal = 32 << 20
)

// highlightBudget is the longest one file may spend being tokenized before
// highlighting is abandoned for plain text. It bounds a hostile file that makes
// the lexer slow without making it fail. A variable so a test can exhaust it.
var highlightBudget = 2 * time.Second

// highlighter turns source text into per-line HTML using chroma, as classed
// spans plus one stylesheet. It runs at generation time and emits no script, so
// the site stays offline (ADR-0029, ADR-0043).
type highlighter struct {
	style     *chroma.Style
	formatter *html.Formatter
	css       template.CSS
	// remaining is how many more bytes this generation may highlight; it starts at
	// maxHighlightTotal and is spent as files are highlighted.
	remaining int
}

// newHighlighter builds a highlighter for the named style. "off" returns nil
// (highlighting disabled). An unknown name falls back to the default style, so a
// typo never breaks generation (ADR-0026).
func newHighlighter(setting string) (*highlighter, error) {
	name := strings.TrimSpace(setting)
	if strings.EqualFold(name, "off") {
		return nil, nil
	}
	style, ok := styles.Registry[name]
	if !ok {
		style = styles.Registry[defaultHighlightStyle]
	}
	if style == nil {
		style = styles.Fallback
	}
	f := html.New(html.WithClasses(true), html.PreventSurroundingPre(true))
	var css bytes.Buffer
	if err := f.WriteCSS(&css, style); err != nil {
		return nil, fmt.Errorf("building highlight stylesheet: %w", err)
	}
	return &highlighter{
		remaining: maxHighlightTotal,
		style:     style,
		formatter: f,
		css:       template.CSS(css.String()), //nolint:gosec // generated by chroma from a built-in style, never from file content
	}, nil
}

// lexerFor picks a lexer from the file name alone (its extension or well-known
// name such as Makefile). Content is never sniffed: guessing a language from
// text mislabels plain files, and a wrong guess is worse than none. It returns
// nil when the name matches no language, including chroma's "plaintext" lexer
// (what *.txt maps to), which has nothing to color and would only attach a
// stylesheet to an ordinary text page.
func lexerFor(filePath string) chroma.Lexer {
	l := lexers.Match(path.Base(filePath))
	if l == nil || l == lexers.Fallback || l.Config().Name == "plaintext" {
		return nil
	}
	return chroma.Coalesce(l)
}

// highlightLines tokenizes text and returns one HTML fragment per source line,
// without line terminators. A token that spans lines (a block comment, a
// multi-line string) is split so every line is self-contained and its tags
// balance. ok is false if tokenizing fails, runs past highlightBudget, or the
// result does not line up with the source, in which case the caller shows plain
// text.
func (h *highlighter) highlightLines(lexer chroma.Lexer, text string, wantLines int) ([]string, bool) {
	it, err := lexer.Tokenise(nil, text)
	if err != nil {
		return nil, false
	}
	deadline := time.Now().Add(highlightBudget)
	var tokens []chroma.Token
	for tok := it(); tok != chroma.EOF; tok = it() {
		tokens = append(tokens, tok)
		if len(tokens)%256 == 0 && time.Now().After(deadline) {
			return nil, false
		}
	}

	lines := make([]string, 0, wantLines)
	for _, lineTokens := range chroma.SplitTokensIntoLines(tokens) {
		// Each line's last token ends with the newline; drop it so the line can
		// sit inside our own per-line span without adding a blank row.
		cleaned := make([]chroma.Token, 0, len(lineTokens))
		for _, t := range lineTokens {
			t.Value = strings.TrimRight(t.Value, "\n")
			if t.Value != "" {
				cleaned = append(cleaned, t)
			}
		}
		var b strings.Builder
		if err := h.formatter.Format(&b, h.style, chroma.Literator(cleaned...)); err != nil {
			return nil, false
		}
		lines = append(lines, b.String())
	}
	// A lexer may add a final newline the source lacked; ignore empty trailing
	// lines on both sides before comparing.
	for len(lines) > wantLines && lines[len(lines)-1] == "" {
		lines = lines[:len(lines)-1]
	}
	if len(lines) != wantLines {
		return nil, false
	}
	return lines, true
}

// codeResult is the rendered body of a file page.
type codeResult struct {
	HTML        template.HTML
	Highlighted bool
	Note        string // why highlighting was skipped, when a language matched
}

// splitSourceLines splits file text into lines. A trailing newline does not start
// another line.
func splitSourceLines(text string) []string {
	lines := strings.Split(text, "\n")
	if n := len(lines); n > 0 && lines[n-1] == "" {
		lines = lines[:n-1]
	}
	return lines
}

// renderCode renders file content as numbered lines. Each line is a span with an
// id (L1, L2, ...) so #L12 links work; the visible number comes from a CSS
// counter, so selecting and copying code does not pick up the numbers. The class
// is "src-line", not a short name, because chroma's own classes include "l" and
// "ln" and must not collide. With a highlighter and a recognized language the
// lines carry token spans; otherwise they are escaped plain text. h may be nil.
func renderCode(data []byte, h *highlighter, filePath string) codeResult {
	text := strings.ToValidUTF8(string(data), "\uFFFD")
	plain := splitSourceLines(text)

	if h != nil {
		if lexer := lexerFor(filePath); lexer != nil {
			switch {
			case len(data) > maxHighlightBytes:
				return wrapLines(escapeLines(plain), false,
					fmt.Sprintf("not highlighted: larger than %s", humanSize(maxHighlightBytes)))
			case len(data) > h.remaining:
				return wrapLines(escapeLines(plain), false,
					"not highlighted: this site's highlighting limit was reached")
			default:
				h.remaining -= len(data)
				if lines, ok := h.highlightLines(lexer, text, len(plain)); ok {
					return wrapLines(lines, true, "")
				}
				return wrapLines(escapeLines(plain), false, "not highlighted: the file could not be tokenized in time")
			}
		}
	}
	return wrapLines(escapeLines(plain), false, "")
}

// escapeLines HTML-escapes each line.
func escapeLines(lines []string) []string {
	out := make([]string, len(lines))
	for i, l := range lines {
		out[i] = template.HTMLEscapeString(l)
	}
	return out
}

// wrapLines puts each already-safe line HTML in its numbered span.
func wrapLines(lines []string, highlighted bool, note string) codeResult {
	var b strings.Builder
	for i, line := range lines {
		fmt.Fprintf(&b, `<span class="src-line" id="L%d">%s</span>`+"\n", i+1, line)
	}
	return codeResult{
		HTML:        template.HTML(b.String()), //nolint:gosec // every line is HTML-escaped by escapeLines or by chroma
		Highlighted: highlighted,
		Note:        note,
	}
}
